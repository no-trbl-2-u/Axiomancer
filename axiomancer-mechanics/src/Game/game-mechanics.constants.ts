// this base), so the saturation-yield route's combined-intensity threshold is
// only reachable when several control effects are active OR this base is raised.
// Symmetric (applies to whoever procs the effect), so the defeat-regression
// guard bounds it; engagement-positive (more decisive status). Tuned by the loop.
export const EFFECT_BASE_PROC_INTENSITY = 2; // Phase 130 — raised from 1 for l15 STRATEGIST targeting

// Phase 157 — Status-centered affix draw bias.
// The affix library (`src/Items/affix.library.ts`) is content-rich with status-
// applying prefixes/suffixes (poison/burn/bleed/stun/fear/curse/sleep/…), but
// most of them sit at `uncommon_mod`/`rare_mod` draw weight (3/1) while the
// flat-stat affixes (Keen/Crushing/Fortified/…) are `common_mod` (10). Left
// unbiased, a weighted affix draw is dominated by boring flat-stat trading and
// the rich status content is mathematically suppressed — a direct violation of
// the load-bearing doctrine ("status effects are the MAIN fun").
//
// This multiplier is applied to the draw weight of OFFENSIVE status-applying
// affixes (status-tagged, on a status-applying slot, not pure defensive/sustain)
// so a roll meaningfully *feeds status-effect play* without erasing flat-stat
// variety entirely. At the default `3`, an uncommon status affix (3×3=9) is
// competitive with a common flat-stat affix (10) and a rare status affix (1×3=3)
// matches an uncommon flat-stat one. Engagement-positive; tuned by the loop.
export const STATUS_AFFIX_DRAW_BIAS = 3;

// ============================================================================
// ENEMY — STAT BUDGET PER LEVEL
// ============================================================================
// Total base-stat budget granted to an enemy is `level × ENEMY_STAT_PER_LEVEL`,
// distributed across heart / body / mind. Players, by contrast, carry a
// `level × 5` budget, so the default `3` makes a same-level enemy roughly 60%
// of a player's raw stat weight — a starting point the tuning workflow A/B's.
//
// This is the single tunable knob for global enemy power scaling. Authored
// enemies that opt into budget-based stats build their `baseStats` via
// `enemyStatBudget(level)` (see `src/Enemy/index.ts`); legacy enemies that
// hand-author `baseStats` are unaffected.
export const ENEMY_STAT_PER_LEVEL = 3;

// Off-budget "gear tier" scaling term to counteract player power accumulation.
// Represents the compounding advantage players gain from equipment upgrades and
// skill library expansion that enemies lack. Applied as a multiplicative bonus
// to enemy defensive stats (HP/defense/resists), weighted away from attack to
// avoid defeat spikes. The curve is ≈0 at level 1 (early game untouched) and
// grows with level to balance late-game trivialization. Magnitude is tuned by
// the mechanics loop via the tunable registry.
export const ENEMY_GEAR_TIER_PER_LEVEL = 0.02;
