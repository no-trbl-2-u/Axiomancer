import { Item, Equipment, EquipmentSlot } from '../Items/types';
import { ActiveEffect } from '../Effects/types';
import { ProcUnlocks } from '../Combat/combat-effects';

/**
 * The three core attributes from which all other character/enemy stats derive.
 *
 * @property heart - Emotion, willpower, charisma. Strong against `body`.
 * @property body  - Physical strength and constitution. Strong against `mind`.
 * @property mind  - Intelligence, reflexes, perception. Strong against `heart`.
 */
export interface BaseStats {
    heart: number;
    body: number;
    mind: number;
}

/**
 * Combat stats derived from BaseStats. Each stance contributes three values:
 * `*Attack` (used in attack rolls), `*Card` (used by skills/philosophy),
 * and `*Defense` (used as damage reduction).
 *
 * `luck` is the average of the three base stats and gates random outcomes.
 */
export interface DerivedStats {
    physicalAttack: number;
    physicalSkill: number;
    physicalDefense: number;
    mentalAttack: number;
    mentalSkill: number;
    mentalDefense: number;
    emotionalAttack: number;
    emotionalSkill: number;
    emotionalDefense: number;
    luck: number;
}

/**
 * Out-of-combat stats — saving throws and ability tests. Player-only.
 * Saves resist effects of that stance; tests are general ability checks.
 */
export interface NonCombatStats {
    physicalSave: number;
    physicalTest: number;
    mentalSave: number;
    mentalTest: number;
    emotionalSave: number;
    emotionalTest: number;
}

/**
 * The player character.
 *
 * @property id                     - Stable identifier (Knowledge-Gaps Q12 /
 *                                    Phase 35). Auto-generated by
 *                                    `createCharacter` from `getRng()` when
 *                                    not supplied by the caller. Mirrors
 *                                    `Enemy.id` so `ActiveEffect.sourceId`
 *                                    can unambiguously point at the applier.
 * @property level                  - Determines stat scaling and abilities.
 * @property experience             - Total XP earned.
 * @property experienceToNextLevel  - XP threshold for the next level-up.
 * @property baseStats              - Heart/Body/Mind core attributes.
 * @property derivedStats           - Combat stats derived from baseStats.
 * @property nonCombatStats         - Saves and ability tests.
 * @property inventory              - Items the character is carrying.
 * @property equipment              - Items currently equipped, keyed by slot.
 *                                    Spec 05 Q1: all seven slots may be
 *                                    occupied simultaneously. Spec 05 Q3:
 *                                    equipment `statModifiers` are folded
 *                                    into `derivedStats` at equip-time, so
 *                                    the character's `derivedStats` is
 *                                    already "post-equipment".
 * @property effects                - Active status effects on the character.
 * @property knownSkills            - IDs of skills the character has learned/unlocked.
 *                                    The combat catalogue is the learned set
 *                                    filtered by affordability (ADR-0002 / Phase
 *                                    99); there is no equipped-skill loadout gate.
 * @property availableStatPoints    - Unspent stat points awaiting allocation
 *                                    (Spec 06 Q3 + Q8). Granted on level-up,
 *                                    spent via `allocateStatPoint`. Defaults
 *                                    to 0 for preset-built characters since
 *                                    presets ship pre-allocated.
 */
export interface Character {
    id: string;
    name: string;
    level: number;
    experience: number;
    experienceToNextLevel: number;
    health: number;
    maxHealth: number;
    baseStats: BaseStats;
    derivedStats: DerivedStats;
    nonCombatStats: NonCombatStats;
    inventory: Item[];
    /**
     * Spec 08 Q8 — generic in-game currency counter. Shops have not landed yet,
     * so only the number is tracked; shop reducers come in a later spec.
     */
    currency: number;
    equipment: Partial<Record<EquipmentSlot, Equipment>>;
    effects: ActiveEffect[];
    knownSkills: string[];
    availableStatPoints: number;
    /**
     * Per-cell Spec 03 proc unlock caps. Defaults to tier 1 in every cell —
     * basic actors only roll the lowest-tier proc table entries. Skills /
     * progression in Spec 04 / 06 raise the cap to unlock T2 / T3 entries.
     */
    procUnlocks?: ProcUnlocks;
    /**
     * Spec 26b deckbuilder — extra combat cards earned as play rewards (skill
     * ids, duplicates allowed), MERGED into the combat deck on top of the cards
     * derived from `knownSkills`. Distinct from `knownSkills`: a reward grows the
     * deck (more copies / variety), while learning a skill (e.g. via an ethical
     * dilemma) unlocks a new card type. Optional + sparse — absent means none.
     */
    combatRewardCards?: string[];
}

/**
 * Hypothetical stat point allocation for previewing derived stats.
 * Each field represents additional points to add to the corresponding base stat.
 */
export interface PreviewAllocation {
    heart: number;
    body: number;
    mind: number;
}

/**
 * Result of previewing stat allocation — computed stats without character mutation.
 */
export interface PreviewResult {
    derivedStats: DerivedStats;
    nonCombatStats: NonCombatStats;
    maxHealth: number;
}
