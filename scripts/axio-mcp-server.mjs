#!/usr/bin/env node
// scripts/axio-mcp-server.mjs — stdio MCP server over the live engine data.
// Zero dependencies; newline-delimited JSON-RPC per the MCP stdio transport.
//
//   node scripts/axio-mcp-server.mjs
//
// Spawned per-session by the MCP host (e.g. Claude Code via .mcp.json) —
// nothing to keep running. Sibling of the KB's kb-mcp-server.mjs
// (kb/scripts/kb-mcp-server.mjs, synced via scripts/kb-sync.mjs): same
// JSON-RPC scaffolding, same accelerator-never-dependency posture, but over
// the repo's OWN generated truth (card/effect/keyword facts) instead of an
// external corpus — see the "axio-query vs kb-query" note in AGENTS.md.
//
// Data source: devlog/data/{cards,enemies,effects}.json, generated by
// `npm run catalog:export` (axiomancer-mechanics/scripts/export-catalog.ts)
// from the live card/enemy/effect libraries, plus
// axiomancer-mechanics/docs/keyword-atlas.md for the 30-keyword registry.
// Freshness is checked lazily on the first tool call (not at handshake time,
// so `initialize`/`tools/list` never block on a multi-second ts-node
// regen) and regenerated when missing or stale. If a regen fails, tools
// serve the last snapshot with a `[STALE]` prefix rather than crashing —
// grep/Read on the source libraries always still works as a fallback.

import { execSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import readline from 'node:readline'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const DATA = path.join(ROOT, 'devlog', 'data')
const MECH = path.join(ROOT, 'axiomancer-mechanics')
const CARDS_LIB = path.join(MECH, 'src', 'Cards', 'cards.library.ts')
const EFFECTS_LIB = path.join(MECH, 'src', 'Effects', 'effects.library.ts')
const KEYWORD_ATLAS = path.join(MECH, 'docs', 'keyword-atlas.md')

const CARDS_JSON = path.join(DATA, 'cards.json')
const ENEMIES_JSON = path.join(DATA, 'enemies.json')
const EFFECTS_JSON = path.join(DATA, 'effects.json')

// --- staleness / regen ------------------------------------------------------
function newestMtime(paths) {
  let max = 0
  for (const p of paths) {
    try { max = Math.max(max, fs.statSync(p).mtimeMs) }
    catch { /* missing source is fine — just doesn't push the bar up */ }
  }
  return max
}

let staleWarning = null
let freshnessChecked = false

function ensureFreshOnce() {
  if (freshnessChecked) return
  freshnessChecked = true
  const exportsExist = [CARDS_JSON, ENEMIES_JSON, EFFECTS_JSON].every((p) => fs.existsSync(p))
  const exportsMtime = exportsExist ? newestMtime([CARDS_JSON, ENEMIES_JSON, EFFECTS_JSON]) : 0
  const sourcesMtime = newestMtime([CARDS_LIB, EFFECTS_LIB])
  if (exportsExist && exportsMtime >= sourcesMtime) { staleWarning = null; return }
  try {
    execSync('npm run catalog:export', { cwd: ROOT, stdio: ['ignore', 'pipe', 'pipe'] })
    staleWarning = null
  }
  catch (err) {
    staleWarning = exportsExist
      ? `axio-query: catalog:export regen failed (${String(err.message).split('\n')[0]}) — serving a stale snapshot.`
      : `axio-query: catalog:export regen failed (${String(err.message).split('\n')[0]}) and no snapshot exists — run "npm run catalog:export" manually.`
  }
}

const withStaleness = (text) => (staleWarning ? `[STALE] ${staleWarning}\n\n${text}` : text)

function loadJson(file) {
  try { return JSON.parse(fs.readFileSync(file, 'utf-8')) }
  catch { return null }
}

const chipValue = (record, key) => record.chips.find((c) => c.k === key)?.v ?? null

// --- keyword atlas (30-row registry: 10 utility + 20 theme hallmarks) ------
function parseKeywordAtlas() {
  if (!fs.existsSync(KEYWORD_ATLAS)) return []
  const lines = fs.readFileSync(KEYWORD_ATLAS, 'utf-8').split(/\r?\n/)
  const rows = []
  let section = null
  for (const line of lines) {
    if (/^##\s+Utility/i.test(line)) { section = 'utility'; continue }
    if (/^##\s+Theme hallmarks/i.test(line)) { section = 'hallmark'; continue }
    if (/^##\s+/.test(line)) { section = null; continue }
    if (!section || !line.trim().startsWith('|')) continue
    const cells = line.split('|').slice(1, -1).map((c) => c.trim())
    if (cells.every((c) => /^:?-+:?$/.test(c))) continue // separator row
    if (section === 'utility' && cells.length === 5) {
      const [keyword, semantics, , gate, notes] = cells
      if (keyword.toLowerCase() === 'keyword') continue // header row
      rows.push({ keyword, type: 'utility', theme: null, semantics, gate: gate.replace(/`/g, ''), notes })
    }
    else if (section === 'hallmark' && cells.length === 6) {
      const [theme, keyword, semantics, , gate, notes] = cells
      if (keyword.toLowerCase() === 'keyword') continue // header row
      rows.push({ keyword, type: 'hallmark', theme, semantics, gate: gate.replace(/`/g, ''), notes })
    }
  }
  return rows
}

// --- doctrine lines (pulled from the library's own header docstring) ------
function extractDoctrine() {
  let text
  try { text = fs.readFileSync(CARDS_LIB, 'utf-8') }
  catch { return [] }
  const header = text.match(/^\/\*\*([\s\S]*?)\*\//)?.[1]
  if (!header) return []
  const paragraphs = header
    .split(/\n\s*\*\s*\n/)
    .map((p) => p.split('\n').map((l) => l.replace(/^\s*\*\/?\s?/, '')).join(' ').replace(/\s+/g, ' ').trim())
    .filter(Boolean)
  return paragraphs.filter((p) => /Direct damage is legal|Rank ladder/.test(p))
}

// --- tools ------------------------------------------------------------------
const TOOLS = [
  {
    name: 'axio_overview',
    description:
      'Counts (cards/enemies/effects), per-theme card counts, rank distribution, keyword-registry coverage, and doctrine one-liners (direct-damage legality, locked systems) sourced from the live libraries. Start here.',
    inputSchema: { type: 'object', properties: {}, additionalProperties: false },
    run() {
      const cards = loadJson(CARDS_JSON) ?? []
      const enemies = loadJson(ENEMIES_JSON) ?? []
      const effects = loadJson(EFFECTS_JSON) ?? []
      const buffs = effects.filter((e) => e.type === 'buff').length
      const debuffs = effects.filter((e) => e.type === 'debuff').length
      const themeCounts = new Map()
      const rankCounts = new Map()
      for (const c of cards) {
        const theme = chipValue(c, 'Theme')
        if (theme) themeCounts.set(theme, (themeCounts.get(theme) ?? 0) + 1)
        const rank = chipValue(c, 'Rank')
        if (rank) rankCounts.set(rank, (rankCounts.get(rank) ?? 0) + 1)
      }
      const keywordRows = parseKeywordAtlas()
      const lines = [
        `# Library — ${cards.length} cards, ${enemies.length} enemies, ${effects.length} effects (${buffs} buff / ${debuffs} debuff)`,
        `# Keyword registry — ${keywordRows.length}/30 rows (${keywordRows.filter((r) => r.type === 'utility').length} utility, ${keywordRows.filter((r) => r.type === 'hallmark').length} hallmark)`,
        `# Themes — ${themeCounts.size}: ${[...themeCounts.entries()].map(([t, n]) => `${t}(${n})`).join(', ') || '(none)'}`,
        `# Ranks — ${[...rankCounts.entries()].map(([r, n]) => `${r}:${n}`).join(', ') || '(none)'}`,
        ...extractDoctrine().map((p) => `# Doctrine — ${p}`),
      ]
      return withStaleness(lines.join('\n'))
    },
  },
  {
    name: 'axio_cards',
    description:
      'Search the live 70-card themed deck library by name / keyword / theme / rank. Returns pricing arithmetic (the "// pts:" comment) + rules text, always as current as the working tree.',
    inputSchema: {
      type: 'object',
      properties: {
        query: { type: 'string', description: 'case-insensitive substring over name, keywords, and rules text' },
        theme: { type: 'string', description: 'exact theme slug, e.g. affliction' },
        rank: { type: 'string', description: 'rank name or number substring, e.g. Axiom or 5' },
        limit: { type: 'number', description: 'default 15' },
      },
      additionalProperties: false,
    },
    run({ query, theme, rank, limit = 15 }) {
      const cards = loadJson(CARDS_JSON)
      if (!cards) return withStaleness('cards.json not found — run "npm run catalog:export".')
      const q = query?.toLowerCase()
      const rankQ = rank != null ? String(rank).toLowerCase() : null
      const hits = cards.filter((c) => {
        if (theme && (chipValue(c, 'Theme') ?? '').toLowerCase() !== theme.toLowerCase()) return false
        if (rankQ && !(chipValue(c, 'Rank') ?? '').toLowerCase().includes(rankQ)) return false
        if (q) {
          const haystack = [c.name, chipValue(c, 'Keywords') ?? '', ...(c.lines ?? [])].join(' ').toLowerCase()
          if (!haystack.includes(q)) return false
        }
        return true
      }).slice(0, limit)
      if (!hits.length) return withStaleness('No cards match.')
      return withStaleness(hits.map((c) =>
        `${c.name} [${chipValue(c, 'Rank') ?? '?'}, ${chipValue(c, 'Theme') ?? chipValue(c, 'Source') ?? '?'}] pricing: ${c.pricing ?? '(none)'}\n  ${c.lines.join(' / ') || '(no rules text)'}`,
      ).join('\n'))
    },
  },
  {
    name: 'axio_effects',
    description:
      'Search the buffs/debuffs libraries by name or id substring. Returns type, tier, duration, stacking, and payload stat lines.',
    inputSchema: {
      type: 'object',
      properties: {
        query: { type: 'string', description: 'case-insensitive substring over name/id' },
        type: { type: 'string', enum: ['buff', 'debuff'] },
        limit: { type: 'number', description: 'default 15' },
      },
      required: ['query'],
      additionalProperties: false,
    },
    run({ query, type, limit = 15 }) {
      const effects = loadJson(EFFECTS_JSON)
      if (!effects) return withStaleness('effects.json not found — run "npm run catalog:export".')
      const q = query.toLowerCase()
      const hits = effects.filter((e) => {
        if (type && e.type !== type) return false
        return e.name.toLowerCase().includes(q) || e.id.toLowerCase().includes(q)
      }).slice(0, limit)
      if (!hits.length) return withStaleness(`No effects match "${query}".`)
      return withStaleness(hits.map((e) =>
        `${e.name} [${e.type}, tier ${chipValue(e, 'Tier') ?? '?'}, ${chipValue(e, 'Duration') ?? '?'}, stacking:${chipValue(e, 'Stacking') ?? '?'}] — ${e.lines.join(' / ') || '(no payload)'}`,
      ).join('\n'))
    },
  },
  {
    name: 'axio_keywords',
    description:
      'The 30-keyword registry (10 utility + 20 theme hallmarks) from docs/keyword-atlas.md: semantics, type/theme classification, and proving-gate status (E/P/D/T). Omit "term" for the full registry.',
    inputSchema: {
      type: 'object',
      properties: { term: { type: 'string', description: 'keyword substring; omit for the full 30-row registry' } },
      additionalProperties: false,
    },
    run({ term } = {}) {
      const rows = parseKeywordAtlas()
      if (!rows.length) return withStaleness(`Keyword atlas not found or empty at ${path.relative(ROOT, KEYWORD_ATLAS)}.`)
      const q = term?.toLowerCase()
      const hits = q ? rows.filter((r) => r.keyword.toLowerCase().includes(q)) : rows
      if (!hits.length) return withStaleness(`No keyword matches "${term}". ${rows.length} total in the registry.`)
      return withStaleness(hits.map((r) =>
        `${r.keyword} [${r.type}${r.theme ? `/${r.theme}` : ''}] gate:${r.gate} — ${r.semantics}${r.notes ? ` (${r.notes})` : ''}`,
      ).join('\n'))
    },
  },
]

// --- JSON-RPC over stdio ---------------------------------------------------
const send = (msg) => process.stdout.write(JSON.stringify(msg) + '\n')
const reply = (id, result) => send({ jsonrpc: '2.0', id, result })
const replyError = (id, code, message) => send({ jsonrpc: '2.0', id, error: { code, message } })

const rl = readline.createInterface({ input: process.stdin, terminal: false })
rl.on('line', (line) => {
  if (!line.trim()) return
  let msg
  try { msg = JSON.parse(line) }
  catch { return }
  const { id, method, params } = msg
  if (method?.startsWith('notifications/')) return
  try {
    if (method === 'initialize') {
      reply(id, {
        protocolVersion: params?.protocolVersion ?? '2024-11-05',
        capabilities: { tools: {} },
        serverInfo: { name: 'axio-query', version: '1.0.0' },
      })
    }
    else if (method === 'ping') reply(id, {})
    else if (method === 'tools/list') {
      reply(id, { tools: TOOLS.map(({ name, description, inputSchema }) => ({ name, description, inputSchema })) })
    }
    else if (method === 'tools/call') {
      const tool = TOOLS.find((t) => t.name === params?.name)
      if (!tool) return replyError(id, -32602, `Unknown tool: ${params?.name}`)
      ensureFreshOnce()
      let text
      try { text = tool.run(params?.arguments ?? {}) }
      catch (err) {
        return reply(id, { content: [{ type: 'text', text: `axio-query internal error: ${err.message}` }], isError: true })
      }
      reply(id, { content: [{ type: 'text', text }] })
    }
    else if (id !== undefined) replyError(id, -32601, `Method not found: ${method}`)
  }
  catch (err) {
    if (id !== undefined) replyError(id, -32603, `Internal error: ${err.message}`)
  }
})
rl.on('close', () => process.exit(0))
